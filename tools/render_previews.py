"""Renders docs/previews/*.svg from pattern_math, so pattern changes can be eyeballed
without touching Onshape.

Run:  python3 tools/render_previews.py   (from the repo root)
"""

import math
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import pattern_math as pm  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "docs", "previews")
REGION = [
    [(0, 0), (80, 0), (80, 30), (40, 30), (40, 60), (0, 60)],
    [(10, 10), (24, 10), (24, 22), (10, 22)][::-1],
]
N = (0.0, 1.0, 0.0)
CASES = [
    # name, print axis vs hole axis (deg), caption
    ("side", 90, "Print Z across the holes (wall printed upright): bridges allowed"),
    ("tilted", 65, "Print Z 65 deg from the hole axis: no bridging, pointed roofs"),
    ("flat", 0, "Print Z along the holes (plate printed flat): any shape"),
]
PATTERNS = [(pm.CIRCLES, 5.0), (pm.HEXAGONS, 6.0), (pm.TRIANGLES, 6.0)]
RIB, MAX_OH, MAX_BRIDGE = 1.6, 45.0, 4.0


def svg_for(kind, cell, beta):
    Z = (0.0, math.cos(math.radians(beta)), math.sin(math.radians(beta)))  # tips toward world +z
    frame = pm.pattern_frame(N, Z, MAX_OH, pattern_angle_deg=0.0, plane_x=(1.0, 0.0, 0.0))
    cs = pm.build_cell_set(kind, cell, RIB, frame, MAX_BRIDGE)
    placed = pm.place_holes(cs, REGION, RIB)
    S, pad = 5.0, 12.0
    W, H = 80 * S + 2 * pad, 60 * S + 2 * pad + 34
    X = lambda x: pad + x * S
    Y = lambda y: pad + 34 + (60 - y) * S
    region_d = " ".join("M " + " L ".join("%.2f %.2f" % (X(x), Y(y)) for x, y in lp) + " Z" for lp in REGION)
    holes = []
    bad = 0
    for c, h in placed:
        poly = pm.placed_outline(c, h, 72)
        if pm.check_printable(pm.outline(h, 180), frame, MAX_BRIDGE):
            bad += 1
        holes.append("M " + " L ".join("%.2f %.2f" % (X(x), Y(y)) for x, y in poly) + " Z")
    title = "%s - %s: %d holes%s" % (kind, cs["label"], len(placed), "" if not bad else " (%d NOT printable)" % bad)
    arrow = ""
    if frame["constrained"]:
        ax, ay = W - pad - 10, 34 + pad + 40
        arrow = ('<line x1="%d" y1="%d" x2="%d" y2="%d" stroke="#c0392b" stroke-width="2.5" marker-end="url(#a)"/>'
                 '<text x="%d" y="%d" font-size="11" fill="#c0392b" text-anchor="end">print up</text>'
                 % (ax, ay + 30, ax, ay - 4, ax - 6, ay + 30))
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">'
        '<defs><marker id="a" markerWidth="8" markerHeight="8" refX="4" refY="4" orient="auto">'
        '<path d="M0,0 L8,4 L0,8 z" fill="#c0392b"/></marker></defs>'
        '<rect width="100%%" height="100%%" fill="#ffffff"/>'
        '<text x="%d" y="20" font-family="sans-serif" font-size="13" fill="#222">%s</text>'
        '<path d="%s" fill="#d9e2ec" stroke="#334e68" stroke-width="1.2" fill-rule="evenodd"/>'
        '<path d="%s" fill="#ffffff" stroke="#102a43" stroke-width="0.8"/>%s</svg>'
        % (W, H, W, H, pad, title, region_d, " ".join(holes), arrow)
    )


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, beta, _ in CASES:
        for kind, cell in PATTERNS:
            with open(os.path.join(OUT, "%s_%s.svg" % (kind, name)), "w") as f:
                f.write(svg_for(kind, cell, beta))
    lines = ["# Pattern previews", "",
             "Generated by `tools/render_previews.py` from the same math the feature uses. "
             "Region: L-shape with a rectangular hole; cell %.0f-%.0f mm, rib %.1f mm, "
             "max overhang %.0f deg, max bridge %.0f mm, edge margin = rib." % (5, 6, RIB, MAX_OH, MAX_BRIDGE), ""]
    for name, beta, caption in CASES:
        lines += ["## " + caption, ""]
        lines += ["![%s %s](%s_%s.svg)" % (k, name, k, name) for k, _ in PATTERNS]
        lines.append("")
    with open(os.path.join(OUT, "README.md"), "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
